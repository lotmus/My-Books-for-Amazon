import sys, docx
from docx.oxml.ns import qn
from model16 import text, style
W=lambda t: qn('w:'+t)
d=docx.Document(sys.argv[1]); rels=d.part.rels
def rtext(r):
    t=''.join(x.text or '' for x in r.iter(W('t')))
    if not t: return ''
    rp=r.find(W('rPr'))
    if rp is not None:
        v=rp.find(W('vertAlign'))
        if v is not None and v.get(W('val'))=='superscript': t='<sup>'+t+'</sup>'
        if v is not None and v.get(W('val'))=='subscript': t='<sub>'+t+'</sub>'
        if rp.find(W('i')) is not None and t.strip(): t='*'+t+'*'
        if rp.find(W('b')) is not None and t.strip(): t='**'+t+'**'
    return t
def ptext(p):
    out=''
    for ch in p:
        if ch.tag==W('r'): out+=rtext(ch)
        elif ch.tag==W('hyperlink'):
            lab=''.join(rtext(r) for r in ch.iter(W('r')))
            rid=ch.get(qn('r:id')); a=ch.get(W('anchor'))
            out+='[%s](%s)'%(lab, rels[rid].target_ref if rid else '#'+a)
    return out.replace('**', '**')
lines=['<!-- Markdown working copy of The_Universe_Actually__REV16.docx (generated by scripts/rev16/tomd.py). The docx is the master. -->','']
figs=iter(sys.argv[2:])
for p in d.element.body.iterchildren(W('p')):
    s=style(p); t=ptext(p)
    bm=[b.get(W('name')) for b in p.iter(W('bookmarkStart')) if not b.get(W('name')).startswith('_')]
    anchor=''.join('<a id="%s"></a>'%b for b in bm)
    if p.findall('.//'+W('drawing')):
        dp=next(p.iter('{http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing}docPr'))
        lines.append('![%s](%s)'%(dp.get('descr',''), next(figs,'figure.png'))); lines.append(''); continue
    if not t.strip() and not anchor: continue
    if s=='Heading1': lines.append('# '+anchor+text(p))
    elif s=='Heading2': lines.append('## '+anchor+text(p))
    elif s=='Heading3': lines.append('### '+anchor+text(p))
    elif s=='Title': lines.append('# '+text(p))
    else: lines.append(anchor+t)
    lines.append('')
open(sys.argv[1].replace('.docx','.md'),'w').write('\n'.join(lines))
print(len(lines))
