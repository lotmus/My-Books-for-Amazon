# ---- 11: one section vs two binomial sections, 50 to 100 ohm (Worked Example 11.1), exact line response
f, ax = fig(8, 4.5); fr = np.linspace(0.5, 4.4, 4000)
def trf(Zs, RLd, fr, f0=2.45):
    Zx = RLd + 0j
    for Zk in reversed(Zs):
        t = np.tan(np.pi/2*fr/f0); Zx = Zk*(Zx + 1j*Zk*t)/(Zk + 1j*Zx*t)
    return abs((Zx-50)/(Zx+50))
ax.plot(fr, trf([70.71], 100, fr), color=BLUE, lw=2.2, label='one quarter-wave section, 70.7 Ω')
ax.plot(fr, trf([59.46, 84.09], 100, fr), color=RED, lw=2.2, label='two binomial sections, 59.5 and 84.1 Ω')
ax.axhline(0.1, color=GRAY, ls='--', lw=1); ax.text(0.55, 0.108, '|Γ| = 0.1 (20 dB return loss)', fontsize=9.5, color=GRAY)
